CREATE TABLE IF NOT EXISTS public.programa_controle (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  controle bigint NOT NULL REFERENCES public.controle (id),
  programa integer NOT NULL REFERENCES public.programa (id),
  nivel integer
);

CREATE TABLE IF NOT EXISTS public.programa_medida (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  programa integer REFERENCES public.programa (id) ON UPDATE CASCADE ON DELETE CASCADE,
  resposta text,
  justificativa text,
  medida integer REFERENCES public.medida (id),
  observacao_orgao text,
  responsavel integer,
  previsao_inicio date,
  previsao_fim date,
  status_medida integer,
  nova_resposta text,
  encaminhamento_interno text,
  controle bigint REFERENCES public.controle (id),
  status_plano_acao integer,
  CONSTRAINT unique_programa_medida UNIQUE (programa, medida)
);

COMMENT ON TABLE public.programa_medida IS 'Cadastro de Medidas';

